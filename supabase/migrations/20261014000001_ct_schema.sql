create or replace function public.ct_tg_contract_before() returns trigger
language plpgsql set search_path = public as $$
begin
  if exists (select 1 from ct_properties where code = new.property_code and accounting_only) then
    new.accounting_only := true;
  end if;
  if tg_op = 'UPDATE' then
    new.updated_at := now();
    new.updated_by := auth.uid();
    new.created_at := old.created_at;
    new.created_by := old.created_by;
  end if;
  return new;
end $$;

drop trigger if exists ct_contract_before on public.ct_contracts;
create trigger ct_contract_before before insert or update on public.ct_contracts
  for each row execute function public.ct_tg_contract_before();

create or replace function public.ct_tg_contract_history() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  v_old jsonb := case when tg_op <> 'INSERT' then to_jsonb(old) end;
  v_new jsonb := case when tg_op <> 'DELETE' then to_jsonb(new) end;
begin
  if tg_op = 'UPDATE' and (v_old - array['updated_at','updated_by']) = (v_new - array['updated_at','updated_by']) then
    return new;
  end if;
  insert into ct_contract_history (contract_id, contract_no, version, action, accounting_only,
                                   changed_by, changed_by_name, old_data, new_data)
  values (coalesce((v_new->>'id')::bigint, (v_old->>'id')::bigint),
          coalesce((v_new->>'contract_no')::bigint, (v_old->>'contract_no')::bigint),
          coalesce((v_new->>'version')::int, (v_old->>'version')::int),
          tg_op,
          coalesce((v_new->>'accounting_only')::boolean, (v_old->>'accounting_only')::boolean, false),
          auth.uid(),
          (select display_name from ct_profiles where user_id = auth.uid()),
          v_old, v_new);
  return coalesce(new, old);
end $$;

drop trigger if exists ct_contract_history on public.ct_contracts;
create trigger ct_contract_history after insert or update or delete on public.ct_contracts
  for each row execute function public.ct_tg_contract_history();

-- 締め済み月の仕訳・実績は変更不可
create or replace function public.ct_tg_period_guard() returns trigger
language plpgsql set search_path = public as $$
declare v_period date;
begin
  v_period := case when tg_op = 'DELETE' then old.period else new.period end;
  if exists (select 1 from ct_periods where period = v_period and status = 'closed') then
    raise exception '% は締め済みのため変更できません', to_char(v_period, 'YYYY年MM月');
  end if;
  if tg_op = 'UPDATE' and old.period <> new.period
     and exists (select 1 from ct_periods where period = old.period and status = 'closed') then
    raise exception '% は締め済みのため変更できません', to_char(old.period, 'YYYY年MM月');
  end if;
  return coalesce(new, old);
end $$;

drop trigger if exists ct_journal_guard on public.ct_journal_entries;
create trigger ct_journal_guard before insert or update or delete on public.ct_journal_entries
  for each row execute function public.ct_tg_period_guard();
drop trigger if exists ct_actuals_guard on public.ct_monthly_actuals;
create trigger ct_actuals_guard before insert or update or delete on public.ct_monthly_actuals
  for each row execute function public.ct_tg_period_guard();

