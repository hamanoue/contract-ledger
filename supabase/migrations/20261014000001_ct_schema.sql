create table if not exists public.ct_contracts (
  id                    bigint generated by default as identity primary key,
  contract_no           bigint  not null,                 -- 契約ID（物件コード×100000＋連番）
  version               integer not null default 1,       -- 枝番
  is_active             boolean not null default true,    -- 有効フラグ
  status                text not null default '契約中'
                        check (status in ('申請中', '契約中', '解約予定', '解約済', '停止')),
  txn_type              text not null default '費用' check (txn_type in ('費用', '収益')),
  property_code         integer not null references public.ct_properties(code),
  vendor_code           integer,
  vendor_name           text,
  contract_name         text not null,
  department            text,                             -- 契約担当部門
  person_in_charge      text,
  signed_date           date,
  service_start         date,
  service_end           date,
  cancel_date           date,
  renewal_type          text,                             -- 自動更新 / 都度更新 / 更新なし
  renewal_notice        text,                             -- 解約通知期限（自由記述）
  notice_months         integer check (notice_months between 0 and 36),
  first_billing_date    date,
  billing_cycle         text,                             -- 月次 / 年次 / 半年 / 従量
  payment_timing        text,                             -- 当月分の支払月（翌月払い 等）
  annual_payment_month  integer check (annual_payment_month between 1 and 12),
  annual_period_note    text,                             -- 年払い その他（対象期間メモ）
  amount_basis          text,                             -- 月額 / 年額 / 従量 / 手入力 / 一括
  amount_excl           numeric(14,0),
  tax_amount            numeric(14,0),
  amount_incl           numeric(14,0) generated always as (amount_excl + coalesce(tax_amount, 0)) stored,
  note                  text,
  tax_code              text references public.ct_tax_codes(name),
  invoice_type          text,
  recognition_method    text,                             -- 月割 / 日割 / 実績 / 手入力
  rounding              text,
  journal_date_rule     text default '月末',
  pl_account_code       integer references public.ct_accounts(code),
  pl_sub_code           text,
  counter_account_code  integer references public.ct_accounts(code),
  counter_sub_code      text,
  annual_start_month    integer check (annual_start_month between 1 and 12),
  accounting_only       boolean not null default false,  -- 総務経理部のみ閲覧
  ringi_no              text,
  contract_url          text,
  note2                 text,
  created_at            timestamptz not null default now(),
  created_by            uuid default auth.uid(),
  updated_at            timestamptz not null default now(),
  updated_by            uuid default auth.uid(),
  unique (contract_no, version)
);
create index if not exists ct_contracts_property_idx on public.ct_contracts(property_code);
create index if not exists ct_contracts_vendor_idx on public.ct_contracts(vendor_code);
comment on table public.ct_contracts is '定期契約マスタ（1行＝契約ID×枝番）';

