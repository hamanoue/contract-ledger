-- 次の契約ID（物件コード×100000＋連番）。本社契約も含めて採番するため definer。
create or replace function public.ct_next_contract_no(p_property_code integer) returns bigint
language sql stable security definer set search_path = public as $$
  select coalesce(max(contract_no), p_property_code::bigint * 100000) + 1
  from ct_contracts
  where contract_no between p_property_code::bigint * 100000 + 1 and p_property_code::bigint * 100000 + 99999
$$;

-- 契約の改定：新しい枝番を作成し、旧枝番は前日付で解約済にする
create or replace function public.ct_create_revision(p_contract_id bigint, p_new_start date) returns bigint
language plpgsql security invoker set search_path = public as $$
declare
  r      ct_contracts;
  v_ver  integer;
  v_id   bigint;
begin
  select * into r from ct_contracts where id = p_contract_id;
  if not found then raise exception '契約が見つかりません'; end if;
  if p_new_start is null then raise exception '新しい開始日を指定してください'; end if;
  if r.service_start is not null and p_new_start <= r.service_start then
    raise exception '新しい開始日は現在の枝番の開始日より後にしてください';
  end if;
  select max(version) + 1 into v_ver from ct_contracts where contract_no = r.contract_no;

  insert into ct_contracts (
    contract_no, version, is_active, status, txn_type, property_code, vendor_code, vendor_name,
    contract_name, department, person_in_charge, signed_date, service_start, service_end, cancel_date,
    renewal_type, renewal_notice, notice_months, first_billing_date, billing_cycle, payment_timing,
    annual_payment_month, annual_period_note, amount_basis, amount_excl, tax_amount, note, tax_code,
    invoice_type, recognition_method, rounding, journal_date_rule, pl_account_code, pl_sub_code,
    counter_account_code, counter_sub_code, annual_start_month, accounting_only, ringi_no,
    contract_url, note2)
  values (
    r.contract_no, v_ver, true, '契約中', r.txn_type, r.property_code, r.vendor_code, r.vendor_name,
    r.contract_name, r.department, r.person_in_charge, null, p_new_start, r.service_end, null,
    r.renewal_type, r.renewal_notice, r.notice_months, null, r.billing_cycle, r.payment_timing,
    r.annual_payment_month, r.annual_period_note, r.amount_basis, r.amount_excl, r.tax_amount, r.note, r.tax_code,
    r.invoice_type, r.recognition_method, r.rounding, r.journal_date_rule, r.pl_account_code, r.pl_sub_code,
    r.counter_account_code, r.counter_sub_code, r.annual_start_month, r.accounting_only, null,
    r.contract_url, r.note2)
  returning id into v_id;

  insert into ct_contract_allocations (contract_id, property_code, label, amount_excl, sort)
    select v_id, property_code, label, amount_excl, sort from ct_contract_allocations where contract_id = p_contract_id;
  insert into ct_contract_items (contract_id, item_name, amount_excl, note, sort)
    select v_id, item_name, amount_excl, note, sort from ct_contract_items where contract_id = p_contract_id;

  update ct_contracts
     set status = '解約済', cancel_date = coalesce(cancel_date, p_new_start - 1)
   where id = p_contract_id;

  return v_id;
end $$;

-- 月次計上額の計算（Excel「02_月次費用」と同じ判定）
create or replace function public.ct_calc_month(p_period date)
returns table (
  contract_id          bigint,
  contract_no          bigint,
  version              integer,
  property_code        integer,
  property_name        text,
  vendor_code          integer,
  vendor_name          text,
  contract_name        text,
  txn_type             text,
  billing_cycle        text,
  payment_timing       text,
  amount_basis         text,
  annual_payment_month integer,
  annual_start_month   integer,
  tax_code             text,
  pl_account_code      integer,
  pl_sub_code          text,
  counter_account_code integer,
  counter_sub_code     text,
  journal_date_rule    text,
  contract_amount_incl numeric,
  judgement            text,
  actual_excl          numeric,
  amount_excl          numeric,
  tax_amount           numeric,
  amount_incl          numeric,
  description          text,
  issues               text
)
language sql stable security invoker set search_path = public as $$
  with m as (
    select date_trunc('month', p_period)::date as d
  ), base as (
    select c.*, p.name as pname, coalesce(t.rate, 0) as rate,
           a.amount_excl as act_excl, a.tax_amount as act_tax, m.d as md,
           (c.status in ('解約予定', '解約済') and c.cancel_date is null) as need_cancel,
           (c.is_active and c.status in ('契約中', '解約予定', '解約済')
             and (c.service_start is null or m.d >= date_trunc('month', c.service_start)::date)
             and case
                   when c.cancel_date is not null then m.d <= c.cancel_date
                   when c.service_end is null then true
                   when c.renewal_type = '自動更新' then true
                   else m.d <= c.service_end
                 end) as act
    from ct_contracts c
    cross join m
    left join ct_properties p      on p.code = c.property_code
    left join ct_tax_codes t       on t.name = c.tax_code
    left join ct_monthly_actuals a on a.contract_id = c.id and a.period = m.d
  ), j as (
    select b.*,
      case
        when b.need_cancel then '要設定'
        when not b.act then '対象外'
        when b.pl_account_code is null or b.counter_account_code is null then '要設定'
        when b.amount_basis in ('従量', '手入力') then
          case when b.act_excl is null then '実績入力待ち' else '実績入力済' end
        when b.billing_cycle = '月次' and b.amount_basis = '月額' and b.amount_excl is not null then '計上'
        when b.billing_cycle = '年次' and b.amount_basis = '年額' and b.amount_excl is not null
             and b.annual_start_month is not null and b.annual_payment_month is not null then '計上'
        else '要設定'
      end as jd
    from base b
  ), v as (
    select j.*,
      case
        when j.jd = '実績入力済' then j.act_excl
        when j.jd = '計上' and j.billing_cycle = '月次' then j.amount_excl
        when j.jd = '計上' then
          case when extract(month from j.md) = j.annual_start_month
               then j.amount_excl - trunc(j.amount_excl / 12) * 11
               else trunc(j.amount_excl / 12) end
      end as ex,
      case
        when j.jd = '実績入力済' then coalesce(j.act_tax, trunc(j.act_excl * j.rate))
        when j.jd = '計上' and j.billing_cycle = '月次' then coalesce(j.tax_amount, trunc(j.amount_excl * j.rate))
        when j.jd = '計上' then
          case when extract(month from j.md) = j.annual_start_month
               then coalesce(j.tax_amount, trunc(j.amount_excl * j.rate))
                    - trunc(coalesce(j.tax_amount, trunc(j.amount_excl * j.rate)) / 12) * 11
               else trunc(coalesce(j.tax_amount, trunc(j.amount_excl * j.rate)) / 12) end
      end as tx
    from j
  )
  select v.id, v.contract_no, v.version, v.property_code, v.pname, v.vendor_code, v.vendor_name,
         v.contract_name, v.txn_type, v.billing_cycle, v.payment_timing, v.amount_basis,
         v.annual_payment_month, v.annual_start_month, v.tax_code,
         v.pl_account_code, v.pl_sub_code, v.counter_account_code, v.counter_sub_code, v.journal_date_rule,
         v.amount_incl,
         v.jd, v.act_excl, v.ex, v.tx, v.ex + v.tx,
         case when v.ex is not null then
           concat_ws(' ', v.pname, v.contract_name, to_char(v.md, 'YYYY"年"FMMM"月分"')) end,
         case
           when v.jd = '要設定' then nullif(concat_ws('／',
             case when v.need_cancel then '解約日未入力' end,
             case when v.amount_excl is null and coalesce(v.amount_basis, '') not in ('従量', '手入力') then '金額未入力' end,
             case when v.pl_account_code is null then '損益科目未入力' end,
             case when v.counter_account_code is null then '相手科目未入力' end,
             case when v.billing_cycle = '年次' and v.annual_payment_month is null then '年払月未入力' end,
             case when v.billing_cycle = '年次' and v.annual_start_month is null then '年払対象開始月未入力' end,
             case when coalesce(v.billing_cycle, '') not in ('月次', '年次')
                    or coalesce(v.amount_basis, '') not in ('月額', '年額', '従量', '手入力')
                    or (v.billing_cycle = '月次' and v.amount_basis = '年額')
                    or (v.billing_cycle = '年次' and v.amount_basis = '月額')
                  then '請求サイクルと金額基準の組合せが計上対象外' end
           ), '')
           when v.jd = '実績入力待ち' then '当月の実績金額を入力してください'
         end
  from v
  order by v.property_code, v.contract_no, v.version
$$;

-- 支払月のずれ（当月分の支払がいつか）。null は自動支払なし
create or replace function public.ct_payment_lag(p_timing text) returns integer
language sql immutable as $$
  select case p_timing
    when '前月払い'   then -1
    when '当月払い'   then 0
    when '翌月払い'   then 1
    when '翌月末'     then 1
    when '翌々月払い' then 2
  end
$$;

-- 月次仕訳の生成（計上＋支払予定）。未出力の自動仕訳は作り直す。
create or replace function public.ct_generate_month(p_period date) returns jsonb
language plpgsql security invoker set search_path = public as $$
declare
  m          date := date_trunc('month', p_period)::date;
  m_end      date := (date_trunc('month', p_period) + interval '1 month - 1 day')::date;
  v_cash     integer;
  v_auto_pay boolean;
  r          record;
  a          record;
  v_date     date;
  v_n_alloc  integer;
  v_sum_alloc numeric;
  v_rest_ex  numeric;
  v_rest_tx  numeric;
  v_ex       numeric;
  v_tx       numeric;
  v_i        integer;
  v_lag      integer;
  v_amt      numeric;
  n_accrual  integer := 0;
  n_payment  integer := 0;
  n_skipped  integer := 0;
begin
  if not (public.ct_is_accounting() and public.ct_can_edit()) then
    raise exception '月次仕訳の生成は総務経理部の編集権限が必要です';
  end if;
  if exists (select 1 from ct_periods where period = m and status = 'closed') then
    raise exception '% は締め済みです', to_char(m, 'YYYY年MM月');
  end if;

  select value::integer into v_cash from ct_settings where key = 'cash_account';
  v_auto_pay := coalesce((select value from ct_settings where key = 'auto_payment'), 'true') = 'true';

  delete from ct_journal_entries where period = m and source = 'auto' and exported_at is null;

  -- (1) 費用・収益の計上
  for r in select * from ct_calc_month(m) where judgement in ('計上', '実績入力済') loop
    if exists (select 1 from ct_journal_entries e where e.period = m and e.source = 'auto'
                 and e.entry_type = 'accrual' and e.contract_id = r.contract_id) then
      n_skipped := n_skipped + 1;  -- 出力済みのため残す
      continue;
    end if;
    v_date := case when r.journal_date_rule = '月初' then m else m_end end;

    select count(*), coalesce(sum(amount_excl), 0) into v_n_alloc, v_sum_alloc
      from ct_contract_allocations where contract_id = r.contract_id;

    v_rest_ex := r.amount_excl;
    v_rest_tx := r.tax_amount;
    v_i := 0;
    for a in
      select property_code as dept, amount_excl as w from ct_contract_allocations
       where contract_id = r.contract_id and v_n_alloc > 0 and v_sum_alloc <> 0
      union all
      select r.property_code, 1 where v_n_alloc = 0 or v_sum_alloc = 0
      order by 2 asc  -- 最後（最大）の行で端数を吸収
    loop
      v_i := v_i + 1;
      if v_i = greatest(v_n_alloc, 1) or v_sum_alloc = 0 then
        v_ex := v_rest_ex; v_tx := v_rest_tx;   -- 端数は最後の行で吸収
      else
        v_ex := trunc(r.amount_excl * a.w / v_sum_alloc);
        v_tx := trunc(r.tax_amount  * a.w / v_sum_alloc);
      end if;
      v_rest_ex := v_rest_ex - v_ex;
      v_rest_tx := v_rest_tx - v_tx;

      if r.txn_type = '収益' then
        insert into ct_journal_entries (period, entry_date, entry_type, source, contract_id, contract_no,
          dr_account, dr_sub_code, dr_dept, dr_vendor, dr_amount, dr_tax_amount, dr_tax_code,
          cr_account, cr_sub_code, cr_dept, cr_vendor, cr_amount, cr_tax_amount, cr_tax_code, description)
        values (m, v_date, 'accrual', 'auto', r.contract_id, r.contract_no,
          r.counter_account_code, r.counter_sub_code, r.property_code, r.vendor_code, v_ex + v_tx, 0, null,
          r.pl_account_code, r.pl_sub_code, a.dept, r.vendor_code, v_ex, v_tx, r.tax_code, r.description);
      else
        insert into ct_journal_entries (period, entry_date, entry_type, source, contract_id, contract_no,
          dr_account, dr_sub_code, dr_dept, dr_vendor, dr_amount, dr_tax_amount, dr_tax_code,
          cr_account, cr_sub_code, cr_dept, cr_vendor, cr_amount, cr_tax_amount, cr_tax_code, description)
        values (m, v_date, 'accrual', 'auto', r.contract_id, r.contract_no,
          r.pl_account_code, r.pl_sub_code, a.dept, r.vendor_code, v_ex, v_tx, r.tax_code,
          r.counter_account_code, r.counter_sub_code, r.property_code, r.vendor_code, v_ex + v_tx, 0, null,
          r.description);
      end if;
      n_accrual := n_accrual + 1;
    end loop;
  end loop;

  -- (2) 支払（入金）予定：経過勘定の取崩し
  if v_auto_pay and v_cash is not null then
    -- 月次契約：当月に支払う分（支払月のずれ分だけ前後の月の計上額）
    for v_lag in select unnest(array[-1, 0, 1, 2]) loop
      for r in
        select * from ct_calc_month((m - make_interval(months => v_lag))::date) c
         where c.judgement in ('計上', '実績入力済') and c.billing_cycle = '月次'
           and ct_payment_lag(c.payment_timing) = v_lag
      loop
        if exists (select 1 from ct_journal_entries e where e.period = m and e.source = 'auto'
                     and e.entry_type = 'payment' and e.contract_id = r.contract_id) then
          continue;
        end if;
        perform public.ct_insert_payment(m, m_end, r.contract_id, r.contract_no, r.txn_type,
          r.counter_account_code, r.counter_sub_code, r.property_code, r.vendor_code, v_cash, r.amount_incl,
          concat_ws(' ', r.property_name, r.contract_name,
                    to_char((m - make_interval(months => v_lag))::date, 'YYYY"年"FMMM"月分"'),
                    case when r.txn_type = '収益' then '入金' else '支払' end));
        n_payment := n_payment + 1;
      end loop;
    end loop;

    -- 年次契約：年払い支払月に年額（税込）を支払
    for r in
      select * from ct_calc_month(m) c
       where c.judgement = '計上' and c.billing_cycle = '年次'
         and c.annual_payment_month = extract(month from m)
    loop
      if exists (select 1 from ct_journal_entries e where e.period = m and e.source = 'auto'
                   and e.entry_type = 'payment' and e.contract_id = r.contract_id) then
        continue;
      end if;
      perform public.ct_insert_payment(m, m_end, r.contract_id, r.contract_no, r.txn_type,
        r.counter_account_code, r.counter_sub_code, r.property_code, r.vendor_code, v_cash, r.contract_amount_incl,
        concat_ws(' ', r.property_name, r.contract_name, '年額',
                  case when r.txn_type = '収益' then '入金' else '支払' end));
      n_payment := n_payment + 1;
    end loop;
  end if;

  return jsonb_build_object('accrual', n_accrual, 'payment', n_payment, 'kept_exported', n_skipped);
end $$;

create or replace function public.ct_insert_payment(
  p_period date, p_date date, p_contract_id bigint, p_contract_no bigint, p_txn_type text,
  p_counter integer, p_counter_sub text, p_dept integer, p_vendor integer, p_cash integer,
  p_amount numeric, p_desc text) returns void
language sql security invoker set search_path = public as $$
  insert into ct_journal_entries (period, entry_date, entry_type, source, contract_id, contract_no,
    dr_account, dr_sub_code, dr_dept, dr_vendor, dr_amount, cr_account, cr_sub_code, cr_dept, cr_vendor, cr_amount, description)
  select p_period, p_date, 'payment', 'auto', p_contract_id, p_contract_no,
         case when p_txn_type = '収益' then p_cash else p_counter end,
         case when p_txn_type = '収益' then null else p_counter_sub end,
         p_dept, p_vendor, p_amount,
         case when p_txn_type = '収益' then p_counter else p_cash end,
         case when p_txn_type = '収益' then p_counter_sub else null end,
         p_dept, p_vendor, p_amount, p_desc
  where coalesce(p_amount, 0) <> 0
$$;

-- 経過勘定の月次残高（契約ID×科目×月）
create or replace function public.ct_accrual_balances(p_from date, p_to date)
returns table (
  period        date,
  account_code  integer,
  account_name  text,
  contract_no   bigint,
  opening       numeric,
  debit         numeric,
  credit        numeric,
  closing       numeric
)
language sql stable security invoker set search_path = public as $$
  with months as (
    select generate_series(date_trunc('month', p_from), date_trunc('month', p_to), interval '1 month')::date as period
  ), acc as (
    select code, name, normal_side from ct_accounts where is_accrual
  ), lines as (
    select e.period, e.contract_no, e.dr_account as account_code, e.dr_amount as debit, 0::numeric as credit
      from ct_journal_entries e
    union all
    select e.period, e.contract_no, e.cr_account, 0, e.cr_amount + e.cr_tax_amount from ct_journal_entries e
    union all
    -- 開始残高は正残方向の金額。借方科目なら借方、貸方科目なら貸方として扱う
    select o.period, o.contract_no, o.account_code,
           case when a.normal_side = '借方' then o.amount else 0 end,
           case when a.normal_side = '貸方' then o.amount else 0 end
      from ct_opening_balances o join acc a on a.code = o.account_code
  ), mv as (
    select l.period, l.contract_no, l.account_code, sum(l.debit) as debit, sum(l.credit) as credit
      from lines l join acc a on a.code = l.account_code
     where l.period <= date_trunc('month', p_to)::date
     group by 1, 2, 3
  ), keys as (
    select distinct contract_no, account_code from mv
  ), grid as (
    select mo.period, k.contract_no, k.account_code from months mo cross join keys k
  ), calc as (
    select g.period, g.contract_no, g.account_code, a.name, a.normal_side,
      coalesce((select sum(case when a.normal_side = '借方' then x.debit - x.credit else x.credit - x.debit end)
                  from mv x where x.contract_no is not distinct from g.contract_no
                    and x.account_code = g.account_code and x.period < g.period), 0) as opening,
      coalesce((select x.debit  from mv x where x.contract_no is not distinct from g.contract_no
                  and x.account_code = g.account_code and x.period = g.period), 0) as debit,
      coalesce((select x.credit from mv x where x.contract_no is not distinct from g.contract_no
                  and x.account_code = g.account_code and x.period = g.period), 0) as credit
    from grid g join acc a on a.code = g.account_code
  )
  select period, account_code, name, contract_no, opening, debit, credit,
         opening + case when normal_side = '借方' then debit - credit else credit - debit end
    from calc
   where opening <> 0 or debit <> 0 or credit <> 0
   order by account_code, contract_no, period
$$;

-- 締め／締め解除
create or replace function public.ct_set_period_status(p_period date, p_status text) returns void
language plpgsql security invoker set search_path = public as $$
begin
  if not (public.ct_is_accounting() and public.ct_can_edit()) then
    raise exception '締め処理は総務経理部の編集権限が必要です';
  end if;
  if p_status = 'open' and not public.ct_is_admin() then
    raise exception '締め解除は管理者のみ可能です';
  end if;
  insert into ct_periods (period, status, closed_at, closed_by)
  values (date_trunc('month', p_period)::date, p_status,
          case when p_status = 'closed' then now() end,
          case when p_status = 'closed' then auth.uid() end)
  on conflict (period) do update
    set status = excluded.status, closed_at = excluded.closed_at, closed_by = excluded.closed_by;
end $$;

