-- ---------------------------------------------------------------------
-- 1. ユーザー権限
-- ---------------------------------------------------------------------
create table if not exists public.ct_profiles (
  user_id      uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default '',
  department   text not null check (department in ('総務経理部', '管理部')),
  role         text not null default 'editor' check (role in ('admin', 'editor', 'viewer')),
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);
comment on table public.ct_profiles is '定期契約アプリの利用者（部署・権限）';

create or replace function public.ct_my_department() returns text
language sql stable security definer set search_path = public as $$
  select department from public.ct_profiles where user_id = auth.uid()
$$;

create or replace function public.ct_is_member() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.ct_profiles where user_id = auth.uid())
$$;

create or replace function public.ct_is_accounting() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.ct_profiles where user_id = auth.uid() and department = '総務経理部')
$$;

create or replace function public.ct_can_edit() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.ct_profiles where user_id = auth.uid() and role in ('admin', 'editor'))
$$;

create or replace function public.ct_is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.ct_profiles where user_id = auth.uid() and role = 'admin')
$$;

-- マスタを編集できる人（管理者 or 総務経理部の編集者）
create or replace function public.ct_can_edit_master() returns boolean
language sql stable security definer set search_path = public as $$
  select public.ct_is_admin() or (public.ct_is_accounting() and public.ct_can_edit())
$$;

